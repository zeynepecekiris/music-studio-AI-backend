"""
Rewarded ads.

The app records each earned reward (POST /ads/rewards) and passes the returned
id to AdMob as custom_data. When server-side verification (SSV) is configured
for the ad unit in the AdMob console, Google calls GET /ads/ssv; we check
Google's ECDSA signature and mark the reward verified.
"""
import base64
import logging
import time
import uuid
from typing import Optional
from urllib.parse import parse_qs

import requests
from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from fastapi import APIRouter, Depends, HTTPException, Request
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from db.models import AdReward, User
from db.session import get_db
from services.auth_service import get_current_user

router = APIRouter(prefix="/ads", tags=["ads"])
logger = logging.getLogger(__name__)

GOOGLE_KEYS_URL = "https://www.gstatic.com/admob/reward/verifier-keys.json"
REWARD_TYPES = ("lyrics", "add_friend")
_keys_cache = {"at": 0.0, "keys": {}}


class RewardRequest(BaseModel):
    reward_type: str = Field(..., pattern="^(lyrics|add_friend)$")
    # Generated by the app before showing the ad and sent to AdMob as custom_data,
    # so the SSV callback can find this row
    id: Optional[uuid.UUID] = None


@router.post("/rewards", status_code=201)
def record_reward(
    req: RewardRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """Log a reward the app says was earned; SSV may verify it later."""
    if req.id and db.query(AdReward).filter(AdReward.id == str(req.id)).first():
        raise HTTPException(status_code=409, detail="Reward already recorded")
    reward = AdReward(user_id=current_user.id, reward_type=req.reward_type)
    if req.id:
        reward.id = str(req.id)
    db.add(reward)
    db.commit()
    return {"id": reward.id, "verified": reward.verified}


def _google_keys() -> dict:
    # Google rotates keys rarely; refresh at most once a day
    if time.time() - _keys_cache["at"] > 24 * 3600 or not _keys_cache["keys"]:
        data = requests.get(GOOGLE_KEYS_URL, timeout=10).json()
        _keys_cache["keys"] = {str(k["keyId"]): k["pem"] for k in data["keys"]}
        _keys_cache["at"] = time.time()
    return _keys_cache["keys"]


def _b64url(s: str) -> bytes:
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def verify_ssv_query(raw_query: str, keys: dict) -> dict:
    """Return the callback params if Google's signature over them is valid."""
    sig_at = raw_query.find("&signature=")
    if sig_at < 0:
        raise ValueError("missing signature")
    message = raw_query[:sig_at].encode()
    params = {k: v[0] for k, v in parse_qs(raw_query, keep_blank_values=True).items()}
    pem = keys.get(params.get("key_id", ""))
    if not pem:
        raise ValueError("unknown key_id")
    public_key = serialization.load_pem_public_key(pem.encode())
    try:
        public_key.verify(_b64url(params["signature"]), message, ec.ECDSA(hashes.SHA256()))
    except InvalidSignature as e:
        raise ValueError("bad signature") from e
    return params


@router.get("/ssv")
def admob_ssv_callback(request: Request, db: Session = Depends(get_db)):
    """AdMob server-side verification callback."""
    raw = request.url.query
    try:
        params = verify_ssv_query(raw, _google_keys())
    except Exception as e:
        logger.warning("Rejected AdMob SSV callback: %s", e)
        raise HTTPException(status_code=400, detail="Invalid signature")

    reward_id: Optional[str] = params.get("custom_data")
    transaction_id = params.get("transaction_id")
    reward = db.query(AdReward).filter(AdReward.id == reward_id).first() if reward_id else None
    if reward and (not params.get("user_id") or params["user_id"] == reward.user_id):
        reward.verified = True
        reward.transaction_id = reward.transaction_id or transaction_id
        db.commit()
    # Always 200 for a valid signature so Google doesn't retry
    return {"ok": True}
